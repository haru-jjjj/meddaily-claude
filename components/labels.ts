export const labelsFor = (language: Language): Labels =>
  language === Language.ENGLISH ? en : language === Language.JAPANESE ? ja : ko;

export const formatDate = (ts: number, language: Language): string => {
  const locale = language === Language.ENGLISH ? 'en-US' : language === Language.JAPANESE ? 'ja-JP' : 'ko-KR';
  return new Date(ts).toLocaleDateString(locale, { month: 'short', day: 'numeric', weekday: 'short' });
};
